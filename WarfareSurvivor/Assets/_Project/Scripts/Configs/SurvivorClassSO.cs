using System.Collections.Generic;
using UnityEngine;

namespace WarfareSurvivor
{
    /// <summary>
    /// Роль бойца в строю. ПОРЯДОК ЗНАЧИМ: он же задаёт порядок колец изнутри
    /// наружу. Кто ничего не делает по площади — в центр, кто бьёт вплотную —
    /// наружу, стрелки между ними.
    /// </summary>
    public enum SquadRole
    {
        /// <summary>Лечит, баффает, сам не атакует. Самое защищённое место — центр.</summary>
        Support = 0,

        /// <summary>Стреляет на дистанции.</summary>
        Ranged = 1,

        /// <summary>Бьёт вблизи — значит стоит там, куда враг приходит первым.</summary>
        Melee = 2
    }

    /// <summary>Форма ударной волны молота.</summary>
    public enum ShockShape
    {
        /// <summary>Круг вокруг бойца: достаётся всем, включая тех, кто за спиной.</summary>
        Circle = 0,

        /// <summary>Сектор в сторону удара: сильнее там, куда бьёт, и никого позади.</summary>
        Directed = 1
    }

    /// <summary>Что волна делает с тем, до кого дошла.</summary>
    public enum ImpactKind
    {
        /// <summary>Отбрасывает. Разряжает толпу, но враг сразу идёт обратно.</summary>
        Knockback = 0,

        /// <summary>С некоторой вероятностью оглушает. Толпа остаётся на месте, но стоит.</summary>
        Stun = 1
    }

