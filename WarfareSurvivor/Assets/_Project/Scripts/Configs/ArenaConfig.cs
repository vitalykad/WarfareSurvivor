    /// <summary>
    /// Все числа тестовой арены в одном месте. Подсказки объясняют не «что это»,
    /// а почему значение такое и что сломается от изменения — см. §8 project.md.
    ///
    /// ВАЖНО про правку этого файла: настроенный ассет удалять нельзя.
    /// Добавление нового поля НЕ требует пересоздания — Unity сохраняет все
    /// уже записанные значения и подставляет умолчание из кода только новому
    /// полю. Удаление ассета не только стирает ручную настройку, но и меняет
    /// его GUID, из-за чего все ссылки на него в сцене превращаются в пустые.
    ///
    /// Переименование поля — единственный случай, когда значение теряется.
    /// Чтобы не потерялось, старое имя помечается атрибутом:
    ///     [UnityEngine.Serialization.FormerlySerializedAs("староеИмя")]
    ///
    /// Сброс к умолчаниям — отдельный пункт меню WarfareSurvivor/Setup,
    /// и только он, никогда не побочный эффект пересборки.
    /// </summary>
    /// <summary>Что именно прогоняет стенд нагрузки.</summary>
    public enum SweepMode
    {
        /// <summary>Растущая толпа: ищем численность, на которой кадр ломается.</summary>
        Ramp = 3,

        /// <summary>Шейдер и тени зомби на закреплённой толпе.</summary>
        Zombies = 4,

        /// <summary>За что платим на зомби: за кости, за аниматор или за пиксели.</summary>
        Skinning = 5,

        /// <summary>Что упирается в процессор на большой толпе.</summary>
        Crowd = 6,

        /// <summary>Все ступени по разу: ищем, что роняет кадр.</summary>
        Full = 0,

        /// <summary>Шейдеры земли по кругу.</summary>
        Ground = 1,

        /// <summary>Масштаб рендера и дальность теней по кругу.</summary>
        Pipeline = 2
    }

    /// <summary>
    /// Одна волна забега. Забег — это последовательность волн, между
    /// которыми игрок успевает выдохнуть.
    ///
    /// Каждая волна задаёт СВОЙ темп спавна и свои тиры, потому что
    /// нарастание сложности здесь и живёт: третья волна должна ощущаться
    /// иначе первой, а не просто длиться дольше.
    /// </summary>
    [System.Serializable]
    public struct WaveEntry
    {
        public string Name;

        [Tooltip("Сколько секунд идёт волна.")]
        public float Duration;

        [Tooltip("Секунд между группами.")]
        public float SpawnInterval;

        public int GroupMin;
        public int GroupMax;

        [Tooltip("Диапазон тиров зомби в этой волне.")]
        public int MinTier;
        public int MaxTier;

        [Tooltip("Потолок живых зомби. Держит кадр в бюджете: цена зомби " +
                 "измерена и линейна, см. PERFORMANCE.md §6.")]
        public int MaxAlive;
    }

    /// <summary>Сколько бойцов какого класса взять в отряд.</summary>
    [System.Serializable]
    public struct SquadEntry
    {
        public SurvivorClassSO Class;
        public int Count;
    }

